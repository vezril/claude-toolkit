#!/usr/bin/env python3
"""Render skills/ats-screening/references/contracts.md from contracts.py.

The model reads the doc; ``edges.py`` enforces the module. If those two were
written separately they would drift, and the drift would show up as the model
being blamed for failing a rule the doc never stated. So the doc is generated,
and a test fails if it is out of date.

    gen_contracts_doc.py            # print
    gen_contracts_doc.py --write    # write the reference file

Standard library only.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import contracts

DOC_PATH = (
    Path(__file__).resolve().parents[2]
    / "skills" / "ats-screening" / "references" / "contracts.md"
)

HEADER = """<!-- Generated by scripts/application-review/gen_contracts_doc.py. Do not edit by hand. -->
# Step contracts

Every step of the review writes one JSON file, and a script checks it before
the next step runs. The checker and this page are generated from the same
definitions in `scripts/application-review/contracts.py`, so what you read here
is exactly what is enforced.

Three rules hold for all five files:

- **No extra fields.** An invented field is rejected by name. If you find
  yourself wanting one, the thing you want to say belongs in a `note`.
- **No blank strings.** A field you have nothing to put in is either `null`
  (where the table says nullable) or a reason to change the status.
- **Quotes are verbatim.** Every `source_quote` and `evidence_quote` is checked
  as a substring of the source text after whitespace normalisation. Tidying the
  punctuation, fixing a typo or joining two sentences all make the check fail.

## Pipeline order

```
CV file ──► [S0 extract.py] ──► parse.json
posting ──► [S1 model] ──► requirements.json ──► schema + posting-quote edge
CV + reqs ──► [S2 model] ──► evidence.json ──► schema + reference + quote edge
                                      │
                                      ▼
                         [S3 verdict.py] ──► verdict.json
                                      │
                      [S4 model] ──► recommendations.json ──► honesty edge
                                      │
                         [S5 render.py] ──► report.md
```
"""

FOOTER = """
## Vocabularies

These lists are closed. A value outside them fails the schema edge.

| Vocabulary | Values |
|---|---|
| Requirement type | {types} |
| Strength | {strengths} |
| Status you may write | {model_statuses} |
| Status the edges may add | {edge_only} |
| Recommendation kind | {kinds} |
| Parse health | {parse_health} |
| Knockout exposure | {knockout} |
| Likely AI tier | {tiers} |
| Language | {languages} |
| Parse signal | {signals} |
| Rank signal | {rank} |
| Flag | {flags} |
| Refusal | {refusals} |

## Parse signals and their severity

Severity is fixed per signal, not chosen. `fatal` makes the file unreadable,
`risk` makes it a structural risk, and `info` never moves parse health at all.

| Signal | Severity | Means |
|---|---|---|
{signal_rows}
"""


def _type_name(spec: dict) -> str:
    base = spec["type"]
    if base == "array":
        item = spec.get("items") or {}
        inner = _type_name(item) if item else "any"
        return f"array of {inner}"
    if base == "object" and spec.get("free_form"):
        return "object (free form)"
    return base


def _rows(fields: dict[str, dict], prefix: str = "") -> list[str]:
    rows: list[str] = []
    for name, spec in fields.items():
        required = "yes" if spec.get("required", True) else "no"
        nullable = " / nullable" if spec.get("nullable") else ""
        notes = [spec["doc"]] if spec.get("doc") else []
        if "enum" in spec:
            notes.append("one of " + ", ".join(f"`{v}`" for v in spec["enum"]))
        if "pattern" in spec:
            notes.append(f"matches `{spec['pattern']}`")
        if spec.get("min_items"):
            notes.append(f"at least {spec['min_items']} item(s)")
        rows.append(
            f"| `{prefix}{name}` | {_type_name(spec)}{nullable} | {required} | "
            + " ".join(notes).replace("|", "\\|")
            + " |"
        )
        if spec["type"] == "object" and spec.get("fields"):
            rows += _rows(spec["fields"], prefix=f"{prefix}{name}.")
        if spec["type"] == "array" and (spec.get("items") or {}).get("fields"):
            rows += _rows(spec["items"]["fields"], prefix=f"{prefix}{name}[].")
    return rows


def generate() -> str:
    parts = [HEADER]
    for name in contracts.STEP_ORDER:
        contract = contracts.CONTRACTS[name]
        parts.append("")
        parts.append(f"## `{contract['file']}` — {contract['step']}, written by {contract['written_by']}")
        parts.append("")
        parts.append(contract["purpose"])
        parts.append("")
        parts.append("| Field | Type | Required | Notes |")
        parts.append("|---|---|---|---|")
        parts += _rows(contract["root"]["fields"])

    def vocab(values) -> str:
        return ", ".join(f"`{v}`" for v in values)

    signal_rows = "\n".join(
        f"| `{code}` | {severity} | {detail} |"
        for code, (severity, detail) in contracts.PARSE_SIGNALS.items()
    )
    parts.append(FOOTER.format(
        types=vocab(contracts.REQUIREMENT_TYPES),
        strengths=vocab(contracts.STRENGTHS),
        model_statuses=vocab(contracts.MODEL_STATUSES),
        edge_only=vocab(sorted(set(contracts.POST_EDGE_STATUSES) - set(contracts.MODEL_STATUSES))),
        kinds=vocab(contracts.RECOMMENDATION_KINDS),
        parse_health=vocab(contracts.PARSE_HEALTH),
        knockout=vocab(contracts.KNOCKOUT_EXPOSURE),
        tiers=vocab(contracts.AI_TIERS),
        languages=vocab(contracts.LANGUAGES),
        signals=vocab(contracts.PARSE_SIGNALS),
        rank=vocab(contracts.RANK_SIGNAL_CODES),
        flags=vocab(contracts.FLAG_CODES),
        refusals=vocab(contracts.REFUSAL_CODES),
        signal_rows=signal_rows,
    ))
    return "\n".join(parts).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="gen_contracts_doc.py")
    parser.add_argument("--write", action="store_true", help=f"write {DOC_PATH}")
    args = parser.parse_args(argv)
    text = generate()
    if args.write:
        DOC_PATH.parent.mkdir(parents=True, exist_ok=True)
        DOC_PATH.write_text(text, encoding="utf-8")
        print(f"wrote {DOC_PATH}")
    else:
        print(text, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
